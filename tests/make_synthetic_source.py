#!/usr/bin/env python3
"""
Regenerate tests/MakeSyntheticNtuple.C from the branches declared in macros/HSCPTemplate.h.

    python3 tests/make_synthetic_source.py

Run it after adding or renaming a TTreeReaderValue / TTreeReaderArray in the header, so that
the synthetic ntuple of the smoke test keeps every branch the selector reads. The event
content (the part after the branch declarations) is kept in this script: edit it here.
"""
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = os.path.join(REPO, "macros", "HSCPTemplate.h")
OUTPUT = os.path.join(REPO, "tests", "MakeSyntheticNtuple.C")

hdr = open(HEADER).read()
vals = re.findall(r'TTreeReaderValue<(\w+)>\s+(\w+)\s*=\s*\{fReader,\s*"([^"]+)"\}', hdr)
arrs = re.findall(r'TTreeReaderArray<(\w+)>\s+(\w+)\s*=\s*\{fReader,\s*"([^"]+)"\}', hdr)

decl, branch, reset = [], [], []
for t, var, br in vals:
    decl.append(f"    {t} {var} = 0;")
    branch.append(f'    tree->Branch("{br}", &{var});')
    reset.append(f"    {var} = 0;")
for t, var, br in arrs:
    decl.append(f"    std::vector<{t}> {var};")
    branch.append(f'    tree->Branch("{br}", &{var});')
    reset.append(f"    {var}.clear();")

NL = "\n"
code = f'''// Synthetic ntuple with every branch read by HSCPSelector, for the smoke test (tests/run_smoke.sh).
// Generated by tests/make_synthetic_source.py from macros/HSCPTemplate.h: do not edit, regenerate.
//
//   root -l -b -q 'tests/MakeSyntheticNtuple.C("file.root", 7)'
//
// Each file holds 4 events (seed shifts the run number only):
//   0  passes everything, candidate above the pT cut (regions C/D, Fpix 0.95)
//   1  same candidate, but no trigger
//   2  passes everything, candidate below the pT cut (regions A/B, Fpix 0.5)
//   3  no candidate
#include <TFile.h>
#include <TTree.h>
#include <TDirectory.h>
#include <vector>
#include <string>
#include <cstdint>

void MakeSyntheticNtuple(const char* fileName = "synthetic.root", int seed = 0) {{
    TFile f(fileName, "RECREATE");
    TDirectory* dir = f.mkdir("HSCPMiniAODAnalyzer");
    dir->cd();
    TTree* tree = new TTree("Events", "synthetic HSCP events");

{NL.join(decl)}

{NL.join(branch)}

    auto resetAll = [&]() {{
{NL.join("    " + r for r in reset)}
    }};

    // One good track: every cut of cfg/selections.json passes (data K/C: C = 2.9784)
    auto addGoodTrack = [&](double pt, float fpix) {{
        HSCP_type.push_back(0); HSCP_hasTrack.push_back(true); PF_type.push_back(211);
        P.push_back(pt * 1.1276);  Pt.push_back(pt); Pterr.push_back(0.05 * pt); Eta.push_back(0.5); Phi.push_back(1.0);
        isHighPurityTrack.push_back(true); dz.push_back(0.01); dxy.push_back(0.001); normChi2.push_back(1.0);
        EoP.push_back(0.05); ptOverptErrptErr.push_back(0.0001); ptOverptErr.push_back(0.05);
        Ih_Strip.push_back(5.0); Ih_Strip_noSF.push_back(5.0); Ih_Strip_oldCorr.push_back(5.0);
        NbPixelHit_noL1.push_back(3); NOM_noL1.push_back(15); FracOfValidHit.push_back(0.9);
        Fpix.push_back(fpix); GStrip.push_back(0.5);
        miniRelIsoAll.push_back(0.01); IsoSumPt_dr03.push_back(5.0);
        Pt_pseudo.push_back(pt); Eta_pseudo.push_back(0.5); Phi_pseudo.push_back(1.0);
        PthatQCD.push_back(0.);
    }};
    // One track failing the pT cut
    auto addBadTrack = [&]() {{
        HSCP_type.push_back(0); HSCP_hasTrack.push_back(true); PF_type.push_back(13);
        P.push_back(30.); Pt.push_back(30.); Pterr.push_back(1.); Eta.push_back(-1.5); Phi.push_back(-2.0);
        isHighPurityTrack.push_back(true); dz.push_back(0.01); dxy.push_back(0.001); normChi2.push_back(1.0);
        EoP.push_back(0.05); ptOverptErrptErr.push_back(0.0001); ptOverptErr.push_back(0.05);
        Ih_Strip.push_back(4.0); Ih_Strip_noSF.push_back(4.0); Ih_Strip_oldCorr.push_back(4.0);
        NbPixelHit_noL1.push_back(3); NOM_noL1.push_back(15); FracOfValidHit.push_back(0.9);
        Fpix.push_back(0.5); GStrip.push_back(0.3);
        miniRelIsoAll.push_back(0.01); IsoSumPt_dr03.push_back(5.0);
        Pt_pseudo.push_back(30.); Eta_pseudo.push_back(-1.5); Phi_pseudo.push_back(-2.0);
        PthatQCD.push_back(0.);
    }};
    auto eventLevel = [&](bool fireMET) {{
        Run = 380000 + seed; PV_npvsGood = 30; weightPU = 1.; weightPU_Up = 1.; weightPU_Down = 1.;
        HLT_PFMET120_PFMHT120_IDTight = fireMET; HLT_FilterOR = fireMET;
        Flag_allMETFilters.push_back(true);
        RecoPUppiMET.push_back(300.); RecoPUppiMET_phi.push_back(0.);
        PseudoCaloMET.push_back(300.); RecoPFMET.push_back(300.);
        L1MET.push_back(100.); HLTCaloMET.push_back(100.); HLTCaloMHT.push_back(100.); HLTPFMHT.push_back(100.); HLTPFMET.push_back(100.);
        // one jet, so that PFMHT = 200 > 120 and the MET trigger condition holds
        Jet_px.push_back(200.); Jet_py.push_back(0.); Jet_pt.push_back(200.);
        Jet_passJetID.push_back(true); Jet_IsRejectedbyJVM.push_back(false); Jet_jesUncTotal.push_back(0.05);
    }};

    // event 0: good track above the pT cut, triggered
    resetAll(); eventLevel(true); addGoodTrack(120., 0.95f); addBadTrack(); HSCP_n = 2; tree->Fill();
    // event 1: same, no trigger
    resetAll(); eventLevel(false); addGoodTrack(120., 0.95f); addBadTrack(); HSCP_n = 2; tree->Fill();
    // event 2: good track below the pT cut, triggered
    resetAll(); eventLevel(true); addBadTrack(); addGoodTrack(60., 0.5f); HSCP_n = 2; tree->Fill();
    // event 3: no candidate
    resetAll(); eventLevel(true); HSCP_n = 0; tree->Fill();

    dir->Write();
    f.Close();
}}
'''
with open(OUTPUT, "w") as f:
    f.write(code)
print(f"{OUTPUT}: {len(vals)} scalar and {len(arrs)} array branches")
